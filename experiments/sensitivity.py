"""Held-out sensitivity study: why is our blocking ratio far below the paper's 0.27 / 0.42 at q = 0.9?

Two readings the paper leaves open could make the network much busier than our baseline:
  gaps:   "Poisson(t_c/4, |R|)" read as gaps between arrivals (cumulative), not arrival times (A3).
  per-slot: a request needs its n pairs in each of its h slots, so n*h pairs in its window (A27).
Each variant swaps only the request generator; the model, methods, seeds and calibration stay fixed.
This runs after Part A and changes no headline result. Writes results/sensitivity.csv and .md.
"""
import _bootstrap  # noqa: F401
import argparse
from dataclasses import replace

import numpy as np
import pandas as pd

import qmp.sim as sim
from experiments.common import calibrated_n_spec, run_pool, write_csv_atomic, write_text_atomic, Timer
from experiments.methods import METHODS
from qmp.model import draw_pairs, make_requests
from qmp.core import Request
from qmp.stats import mean_ci

ROOT = _bootstrap.ROOT
METHOD_NAMES = ["SP-Heu", "MP-Heu", "SP-ILP", "MP-ILP"]
VARIANTS = ["baseline", "gaps", "per-slot", "gaps+per-slot"]


def requests_with_gaps(rng, nodes, R, T, tc, n_spec, f):
    """Same draws as make_requests, but arrivals are cumulative Poisson gaps; requests past T are dropped."""
    nodes = sorted(nodes)
    out, clock = [], 0
    for rid in range(R):
        s = nodes[int(rng.integers(len(nodes)))]
        others = [v for v in nodes if v != s]
        d = others[int(rng.integers(len(others)))]
        clock += int(rng.poisson(tc / 4))
        a = max(1, clock)
        h = int(rng.integers(1, 5))
        n = draw_pairs(rng, n_spec)
        if a + h + 1 > T:
            continue  # cannot fit before T; it never enters the network (counted as blocked below)
        b = int(rng.integers(a + h + 1, T + 1))
        out.append(Request(id=rid, s=s, d=d, n=n, a=a, h=h, b=b, f=f))
    return out


def per_slot(base):
    """Wrap a generator so each request needs n pairs per execution slot (n * h in total)."""
    def gen(*args):
        return [replace(r, n=r.n * r.h) for r in base(*args)]
    return gen


GENERATORS = {"baseline": make_requests, "gaps": requests_with_gaps,
              "per-slot": per_slot(make_requests), "gaps+per-slot": per_slot(requests_with_gaps)}


def run_one(job: dict) -> dict:
    """Worker: swap the request generator for this variant, then simulate."""
    sim.make_requests = GENERATORS[job["variant"]]
    cfg = sim.SimConfig(3, 3, 60, 6, 100, 10, job["q"], 0.95, 0.78, job["n_spec"], job["seed"])
    res = sim.simulate(cfg, METHODS[job["method"]])
    # Requests dropped before entering (gaps variant) count as blocked: divide by the full |R| = 60.
    blocking = (cfg.R - len(res.placed)) / cfg.R
    return dict(variant=job["variant"], method=job["method"], q=job["q"], seed=job["seed"],
                blocking_ratio=blocking, gamma=res.gamma, windows_time_limit=res.time_limit_windows)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=12)
    ap.add_argument("--seeds", type=int, default=30)
    args = ap.parse_args()
    n_spec = calibrated_n_spec()
    jobs = [dict(variant=v, method=m, q=q, seed=s, n_spec=n_spec)
            for v in VARIANTS for m in METHOD_NAMES for q in (0.5, 0.9) for s in range(args.seeds)]
    with Timer():
        df = pd.DataFrame(run_pool(run_one, jobs, args.workers))
    write_csv_atomic(df, ROOT / "results" / "sensitivity.csv")
    lines = ["# Sensitivity of the blocking-ratio level (held out, after Part A)", "",
             f"n = {n_spec} (calibrated), 3x3 grid, |R| = 60, {args.seeds} seeds. Mean ± 95% CI half-width.",
             "Paper at q = 0.9: MP-ILP 0.27, SP-ILP 0.42 (printed).", "",
             "| variant | method | q = 0.5 | q = 0.9 | time-limited windows |", "|---|---|---|---|---|"]
    for v in VARIANTS:
        for m in METHOD_NAMES:
            cells = []
            for q in (0.5, 0.9):
                x = df[(df.variant == v) & (df.method == m) & (df.q == q)]["blocking_ratio"]
                mu, hw = mean_ci(list(x))
                cells.append(f"{mu:.2f} ± {hw:.2f}")
            tl = int(df[(df.variant == v) & (df.method == m)]["windows_time_limit"].sum())
            lines.append(f"| {v} | {m} | {cells[0]} | {cells[1]} | {tl} |")
    write_text_atomic("\n".join(lines) + "\n", ROOT / "results" / "sensitivity.md")
    write_text_atomic(macros(df), ROOT / "report" / "sensitivity.tex")
    print("\n".join(lines))


def macros(df: pd.DataFrame) -> str:
    """LaTeX macros such as \\sensBRPerSlotMPILPqNine (mean) and \\sensCIPerSlotMPILPqNine (95% CI half-width)."""
    vname = {"baseline": "Base", "gaps": "Gaps", "per-slot": "PerSlot", "gaps+per-slot": "GapsPerSlot"}
    qname = {0.5: "Five", 0.9: "Nine"}
    out = ["% Generated by experiments/sensitivity.py. Do not edit."]
    for (v, m, q), g in df.groupby(["variant", "method", "q"]):
        mu, hw = mean_ci(list(g["blocking_ratio"]))
        key = f"{vname[v]}{m.replace('-', '')}q{qname[q]}"
        out += [f"\\newcommand{{\\sensBR{key}}}{{{mu:.2f}}}", f"\\newcommand{{\\sensCI{key}}}{{{hw:.2f}}}"]
    seeds = df["seed"].nunique()
    out.append(f"\\newcommand{{\\sensSeeds}}{{{seeds}}}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    main()
